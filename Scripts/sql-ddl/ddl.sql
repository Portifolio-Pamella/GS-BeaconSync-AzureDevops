-- ---------------------------------------------------------------------
-- 1. TABELA DE ENDEREÇOS
-- ---------------------------------------------------------------------
CREATE TABLE TB_ENDERECO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1,
    LOGRADOURO VARCHAR2(150) NOT NULL,
    CEP VARCHAR2(10) NOT NULL,
    CIDADE VARCHAR2(100) NOT NULL,
    ESTADO VARCHAR2(2) NOT NULL,
    CONSTRAINT PK_ENDERECO PRIMARY KEY (ID)
);

-- ---------------------------------------------------------------------
-- 2. TABELA DE VOLUNTÁRIOS
-- ---------------------------------------------------------------------
CREATE TABLE TB_VOLUNTARIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1,
    NOME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    TELEFONE VARCHAR2(20),
    CONSTRAINT PK_VOLUNTARIO PRIMARY KEY (ID),
    CONSTRAINT UK_VOLUNTARIO_EMAIL UNIQUE (EMAIL)
);

-- ---------------------------------------------------------------------
-- 3. TABELA DE RESPONSÁVEIS
-- ---------------------------------------------------------------------
CREATE TABLE TB_RESPONSAVEL (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1,
    NOME VARCHAR2(150) NOT NULL,
    TELEFONE VARCHAR2(20) NOT NULL,
    EMAIL VARCHAR2(150),
    CONSTRAINT PK_RESPONSAVEL PRIMARY KEY (ID)
);

-- ---------------------------------------------------------------------
-- 4. TABELA DE PESSOAS VULNERÁVEIS
-- ---------------------------------------------------------------------
CREATE TABLE TB_PESSOA_VULNERAVEL (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1,
    NOME VARCHAR2(150) NOT NULL,
    IDADE NUMBER(3) NOT NULL,
    TIPO_VULNERABILIDADE VARCHAR2(100) NOT NULL,
    NECESSIDADE_ESPECIAL VARCHAR2(255),
    ENDERECO_ID NUMBER NOT NULL,
    CONSTRAINT PK_PESSOA_VULNERAVEL PRIMARY KEY (ID),
    CONSTRAINT FK_PESSOA_ENDERECO FOREIGN KEY (ENDERECO_ID) 
        REFERENCES TB_ENDERECO (ID) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 5. TABELA DE RESPOSTAS A ALERTAS
-- ---------------------------------------------------------------------
CREATE TABLE TB_RESPOSTA_ALERTA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1,
    DESCRICAO VARCHAR2(500) NOT NULL,
    STATUS VARCHAR2(50) NOT NULL,
    DATA_RESPOSTA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VOLUNTARIO_ID NUMBER NOT NULL,
    PESSOA_VULNERAVEL_ID NUMBER NOT NULL,
    CONSTRAINT PK_RESPOSTA_ALERTA PRIMARY KEY (ID),
    CONSTRAINT FK_RESPOSTA_VOLUNTARIO FOREIGN KEY (VOLUNTARIO_ID) 
        REFERENCES TB_VOLUNTARIO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RESPOSTA_PESSOA FOREIGN KEY (PESSOA_VULNERAVEL_ID) 
        REFERENCES TB_PESSOA_VULNERAVEL (ID) ON DELETE CASCADE
);

